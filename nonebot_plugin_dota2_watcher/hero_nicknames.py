def _build_reverse_map():
    """构建 昵称(小写) -> [官方中文名, ...] 的反向映射。"""
    rev = {}
    for cn_name, nicks in _HERO_NICKNAMES.items():
        for nick in nicks:
            rev.setdefault(nick.lower(), []).append(cn_name)
    return rev


# 昵称(小写) -> 官方中文名列表
NICKNAME_TO_HEROES = _build_reverse_map()


def resolve_nickname(nick):
    """根据昵称返回官方中文名（大小写不敏感）。

    如果昵称对应多个英雄，随机返回其中一个。
    找不到时返回 None。
    """
    heroes = NICKNAME_TO_HEROES.get(nick.lower())
    if not heroes:
        return None
    return random.choice(heroes)


